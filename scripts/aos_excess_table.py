r"""AoS revision (2026-11-21): the table and number macros of Section S4 "A simulation on the line" (the excess of the
population ramp, Proposition prop:excess of the main text).

Input: the per-replicate files explore/split_rate_excess/out/raw/{kernel}_{design}_n{n}_r{rep}.json, written by
explore/split_rate_excess/scripts/mc_rate.py (read-only here). Each file holds alpha_star and the four bounds of one
replicate: lo_own (the split-sample bound of the paper, own-term cut points), lo_plain, analytic (threshold
min(tau^P, tau^A)) and ks_lb (Kolmogorov-Smirnov statistic minus two DKW-Massart radii). Laws on the line:
S: P = N(1,1), Q = N(-1,1); M: P = 0.8 N(0,1) + 0.2 N(1.5,1), Q = 0.8 N(0,1) + 0.2 N(-1.5,1). Kernels
exp(-(x-y)^2/2) ("gauss") and exp(-|x-y|) ("laplace"), n = m, delta = 0.05, levels alpha* - 0.4 * 0.85^j (S) and
alpha* - 0.12 * 0.85^j (M).

Error = alpha* - bound. Slopes: least squares of log(mean error) on log n over the sample sizes in [NMIN, NMAX] with
at least 5 replicates; standard errors from 2000 bootstrap resamples of the replicates within each n (seed 0). The
KS column is taken from the Laplace runs (the statistic does not depend on the kernel; those runs go to n = 51200).

    python3 -I scripts/aos_excess_table.py
"""
from __future__ import annotations

import json
import math
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "explore" / "split_rate_excess" / "out" / "raw"
OUT_TAB = ROOT / "results" / "aos" / "tables" / "aos_excess_mc.tex"
OUT_MAC = ROOT / "results" / "aos" / "tables" / "aos_excess_macros.tex"
NMIN, NMAX_COMMON = 800, 12800
NS_TABLE = [800, 1600, 3200, 6400, 12800, 25600, 51200]
B = 2000


def load():
    recs = defaultdict(list)
    for f in sorted(RAW.glob("*.json")):
        r = json.loads(f.read_text())
        a = r["alpha_star"]
        recs[(r["kernel"], r["design"], int(r["n"]))].append(
            {"own": a - r["lo_own"], "analytic": a - r["analytic"] if r["analytic"] is not None else math.nan,
             "KS": a - r["ks_lb"]})
    return recs


def slope(ns, ys):
    x = np.log(np.asarray(ns, float))
    A = np.vstack([x, np.ones_like(x)]).T
    return float(np.linalg.lstsq(A, np.log(ys), rcond=None)[0][0])


def slope_se(recs, kernel, design, col, nmax):
    ns = [n for (k, d, n) in recs if k == kernel and d == design and NMIN <= n <= nmax and len(recs[(k, d, n)]) >= 5]
    ns = sorted(ns)
    samples = [np.array([r[col] for r in recs[(kernel, design, n)]]) for n in ns]
    if any(np.isnan(s).any() for s in samples):
        return None
    est = slope(ns, [s.mean() for s in samples])
    rng = np.random.default_rng(0)
    boots = [slope(ns, [rng.choice(s, size=len(s)).mean() for s in samples]) for _ in range(B)]
    return est, float(np.std(boots, ddof=1)), ns


def fmt(x, d=4):
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def grid_constants():
    """The grid of explore/split_rate_excess/scripts/mc_rate.py: alpha* - eps_max * R_GRID^j."""
    src = (ROOT / "explore" / "split_rate_excess" / "scripts" / "mc_rate.py").read_text()
    r = re.search(r"^R_GRID = ([0-9.]+)$", src, re.M).group(1)
    out = {"r": r}
    for des in ("S", "M"):
        out[des] = re.search(r"'" + des + r"': dict\([^)]*eps_max=([0-9.]+)", src).group(1)
        out["min" + des] = f'{float(re.search(r"\'" + des + r"\': dict\([^)]*eps_min=([0-9.e-]+)", src).group(1)):g}'
    m = re.search(r"tol=([0-9.e-]+), maxit=(\d+)\)", src)
    out["wolfe_tol"], out["wolfe_maxit"] = float(m.group(1)), int(m.group(2))
    return out


def wolfe_capped(maxit):
    """Fraction of the Gaussian fits (batches 1 and 2 at every level) that reached the iteration cap of Wolfe's
    algorithm (field 'it' of each fit record)."""
    tot = cap = 0
    for f in sorted(RAW.glob("gauss_*.json")):
        for row in json.loads(f.read_text())["rows"]:
            for key in ("b1", "b2"):
                b = row.get(key)
                if isinstance(b, dict) and "it" in b:
                    tot += 1
                    cap += b["it"] >= maxit - 1
    return cap / tot


def main():
    grid = grid_constants()
    recs = load()
    mean = {k: float(np.mean([r[c] for r in v])) if v else math.nan
            for k0, v in recs.items() for c in ("own", "analytic", "KS") for k in [(k0, c)]}
    reps = {k: len(v) for k, v in recs.items()}
    cols = [("gauss", "own"), ("laplace", "own"), ("laplace", "analytic"), ("laplace", "KS")]
    lines = [r"% generated by scripts/aos_excess_table.py; do not edit",
             r"\begin{tabular}{r cccc @{\hspace{1.2em}} cccc}",
             r"\toprule",
             r" & \multicolumn{4}{c}{Shift, $\alpha^\star=0.683$} & \multicolumn{4}{c}{Mixture, $\alpha^\star=0.173$}\\",
             r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
             r"$n$ & $\widehat\alpha$, G & $\widehat\alpha$, L & $\widehat\alpha_{\mathrm{an}}$, L & KS"
             r" & $\widehat\alpha$, G & $\widehat\alpha$, L & $\widehat\alpha_{\mathrm{an}}$, L & KS\\",
             r"\midrule"]
    for n in NS_TABLE:
        cells = []
        for des in ("S", "M"):
            for kern, col in cols:
                key = (kern, des, n)
                cells.append(fmt(mean.get((key, col), math.nan)) if reps.get(key, 0) >= 5 else "--")
        lines.append(f"{n} & " + " & ".join(cells) + r"\\")
    lines.append(r"\midrule")
    srow = {}
    for nmax, lab in ((NMAX_COMMON, r"slope, $n\le12800$"), (10 ** 9, r"slope, all $n\ge800$")):
        cells = []
        for des in ("S", "M"):
            for kern, col in cols:
                if kern == "gauss" and nmax > NMAX_COMMON:
                    cells.append("")
                    continue
                s = slope_se(recs, kern, des, col, nmax)
                srow[(kern, des, col, nmax)] = s
                cells.append("--" if s is None else f"${s[0]:.2f}\\,({s[1]:.3f})$")
        lines.append(f"{lab} & " + " & ".join(cells) + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT_TAB.parent.mkdir(parents=True, exist_ok=True)
    OUT_TAB.write_text("\n".join(lines) + "\n")

    def mac(name, val):
        return f"\\newcommand{{\\{name}}}{{{val}}}"

    def sl(kern, des, col, nmax):
        s = srow[(kern, des, col, nmax)]
        return f"{-s[0]:.2f}"

    rmin = min(v for (k, d, n), v in reps.items() if NMIN <= n)
    rmax = max(v for (k, d, n), v in reps.items() if NMIN <= n)
    ratio_S = mean[(("laplace", "S", 51200), "KS")] / mean[(("laplace", "S", 51200), "own")]
    ratio_M = mean[(("laplace", "M", 51200), "KS")] / mean[(("laplace", "M", 51200), "own")]
    below = all(mean[(("laplace", d, n), "own")] < mean[(("laplace", d, n), "KS")]
                for d in ("S", "M") for n in NS_TABLE if reps.get(("laplace", d, n), 0) >= 5)
    assert below, "the Laplace split-sample bound is not below KS at every n: revise the text"
    macs = [r"% generated by scripts/aos_excess_table.py; do not edit",
            mac("exLapSlopeS", sl("laplace", "S", "own", 10 ** 9)),
            mac("exLapSlopeM", sl("laplace", "M", "own", 10 ** 9)),
            mac("exGaussSlopeS", sl("gauss", "S", "own", NMAX_COMMON)),
            mac("exGaussSlopeM", sl("gauss", "M", "own", NMAX_COMMON)),
            mac("exLapSlopeCommonS", sl("laplace", "S", "own", NMAX_COMMON)),
            mac("exLapSlopeCommonM", sl("laplace", "M", "own", NMAX_COMMON)),
            mac("exKSSlopeS", sl("laplace", "S", "KS", 10 ** 9)),
            mac("exKSSlopeM", sl("laplace", "M", "KS", 10 ** 9)),
            mac("exAnSlopeS", sl("laplace", "S", "analytic", 10 ** 9)),
            mac("exAnSlopeM", sl("laplace", "M", "analytic", 10 ** 9)),
            mac("exKSRatioS", f"{ratio_S:.1f}"), mac("exKSRatioM", f"{ratio_M:.1f}"),
            mac("exRepMin", str(rmin)), mac("exRepMax", str(rmax)),
            mac("exNmax", "51200"), mac("exNmaxGauss", "12800"),
            mac("exGridS", grid["S"]), mac("exGridM", grid["M"]), mac("exGridRatio", grid["r"]),
            mac("exGridPct", str(round(100 * (1 - float(grid["r"]))))),
            mac("exGridMinS", grid["minS"]), mac("exGridMinM", grid["minM"]),
            mac("exWolfeTol", "10^{%d}" % round(math.log10(grid["wolfe_tol"]))),
            mac("exWolfeMaxit", f'{grid["wolfe_maxit"]:,}'.replace(",", "{,}")),
            mac("exWolfeCapPct", f"{100 * wolfe_capped(grid['wolfe_maxit']):.1f}")]
    OUT_MAC.write_text("\n".join(macs) + "\n")
    print(OUT_TAB.read_text())
    print(OUT_MAC.read_text())


if __name__ == "__main__":
    main()
