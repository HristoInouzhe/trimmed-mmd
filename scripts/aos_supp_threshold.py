r"""AoS supplement, Section S6.1 (cold read COLDREAD_SUPP_59470ea, item I1): the boundary calibration with tau^P.

The null-boundary calibration of the analytic test (scenario disjoint_d2_a20: standard Gaussian core in d = 2,
contaminations uniform on two disjoint boxes, alpha* = 0.2, n = m = 300, 400 replicates, delta = 0.05, Gaussian
kernel) stores, at each level, the empirical 1 - delta quantile q_dhat of the statistic D-hat_alpha and the threshold
it was compared with (column analytic_tau, the minimum of tau^P, tau^S and two numerically inverted versions of tau^P,
which is valid and nowhere larger than tau^P). No simulation here: this script reads

    results/v2/tables/e1_calibration.csv

recomputes tau^P(alpha) of Theorem 3.1 in closed form (trimmedmmd.threshold.tau_plugin_closed, Gaussian constants
kappa = 1, Delta_phi = sqrt 2), checks it against a direct evaluation of the displayed formula, and writes the ratio
tau^P / q_dhat at alpha = alpha* together with the rejection count under tau^P (never above the stored count, as
tau^P is at least the stored threshold) to

    results/aos/tables/aos_supp_threshold_macros.tex      (prefix \st)

    ~/.venvs/llm_book/bin/python -B scripts/aos_supp_threshold.py
"""
from __future__ import annotations

import csv
import math
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from trimmedmmd import threshold as TH  # noqa: E402

SRC = ROOT / "results" / "v2" / "tables" / "e1_calibration.csv"
OUT = ROOT / "results" / "aos" / "tables" / "aos_supp_threshold_macros.tex"


def r1(x):
    return str(Decimal(repr(float(x))).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))


def tau_p_formula(n, m, alpha, delta, kappa=1.0, dphi=math.sqrt(2.0)):
    """Theorem 3.1 as printed: n_star = nm/(n+m), c = max(1/n,1/m), L = log(6/delta), kbar^2 = min(kappa^2, Dphi^2/2)."""
    ns = n * m / (n + m)
    kb2 = min(kappa ** 2, dphi ** 2 / 2)
    if alpha == 0:
        return math.sqrt(kb2) / math.sqrt(ns) + dphi * math.sqrt(math.log(1 / delta) / (2 * ns))
    beta = 1 / (1 - alpha)
    L = math.log(6 / delta)
    c = max(1 / n, 1 / m)
    return (math.sqrt(beta * kb2 / ns) + beta * dphi * math.sqrt(L / (2 * ns))
            + dphi * (math.sqrt(2 * (beta - 1) * L / ns) + c * L / 3))


def main():
    rows = [r for r in csv.DictReader(open(SRC)) if r["scenario"] == "disjoint_d2_a20" and r["n"] == "300"]
    bnd = [r for r in rows if abs(float(r["alpha"]) - float(r["alpha_star"])) < 1e-9]
    assert len(bnd) == 1, bnd
    b = bnd[0]
    n = m = int(b["n"])
    a, d = float(b["alpha"]), float(b["delta"])
    tp = TH.tau_plugin_closed(n, m, a, d, TH.GAUSSIAN)
    assert abs(tp - tau_p_formula(n, m, a, d)) < 1e-12 * tp, (tp, tau_p_formula(n, m, a, d))
    stored = float(b["analytic_tau"])
    assert stored <= tp + 1e-12, (stored, tp)          # the stored threshold is nowhere larger than tau^P
    q = float(b["q_dhat"])
    ratio = tp / q
    print(f"n = m = {n}, alpha = alpha* = {a}, delta = {d}: tau^P = {tp:.4f}, stored threshold = {stored:.4f}, "
          f"empirical {1 - d:.2f}-quantile of D-hat = {q:.4f}, ratio tau^P / quantile = {ratio:.2f} "
          f"(stored threshold: {stored / q:.2f}); rejection rate with the stored threshold {b['reject_rate']}, "
          f"so with tau^P at most that")
    lines = ["% Generated by scripts/aos_supp_threshold.py -- do not edit.",
             f"\\newcommand{{\\stCalibRatioTauP}}{{{r1(ratio)}}}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
