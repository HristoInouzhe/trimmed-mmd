"""AoS referee runs: checks that the defaults of the modified scripts reproduce the stored outputs. Each stage compares
files and appends a line to results/aos/main/ref_realdata/default_checks.json (read by aos_ref_realdata_tables.py).

    python3 -B scripts/aos_ref_realdata_defaults.py tables BACKUP      # after aos_main_tables.py --rhc-covariates paper
    python3 -B scripts/aos_ref_realdata_defaults.py cohort BACKUP      # after aos_main_cohort.py --covariates paper
    python3 -B scripts/aos_ref_realdata_defaults.py cohortrun DIR      # aos_realdata_cohort.py default rerun in DIR
    python3 -B scripts/aos_ref_realdata_defaults.py analytic DIR       # exp_valid_bandwidth.py --datasets rhc in DIR

BACKUP holds copies of the outputs taken before any script was modified (tables/, main/).
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TAB = ROOT / "results" / "aos" / "tables"
MAIN = ROOT / "results" / "aos" / "main"
OUT = MAIN / "ref_realdata" / "default_checks.json"


def record(key, line, detail):
    d = json.loads(OUT.read_text()) if OUT.exists() else {"lines": [], "detail": {}}
    d["detail"][key] = detail
    d["lines"] = [x for x in d["lines"] if not x.startswith(f"[{key}]")] + [f"[{key}] {line}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(d, indent=1))
    print(line)


def same_files(pairs):
    res = {}
    for a, b in pairs:
        ta, tb = Path(a).read_text(), Path(b).read_text()
        if ta == tb:
            res[Path(a).name] = "identical"
        else:
            la, lb = ta.splitlines(), tb.splitlines()
            diff = [i for i, (x, y) in enumerate(zip(la, lb)) if x != y] + (
                [min(len(la), len(lb))] if len(la) != len(lb) else [])
            res[Path(a).name] = {"differing_lines": len(diff), "first": diff[:5],
                                 "examples": [(la[i] if i < len(la) else None, lb[i] if i < len(lb) else None)
                                              for i in diff[:3]]}
    return res


def main():
    stage, arg = sys.argv[1], Path(sys.argv[2])
    if stage == "tables":
        files = ["aos_main_n80.tex", "aos_main_n80_heldout.tex", "aos_main_n80_gauss.tex",
                 "aos_main_recovery_gauss.tex", "aos_main_realdata.tex", "aos_main_macros.tex"]
        pairs = [(arg / "tables" / f, TAB / f) for f in files] + [
            (arg / "main" / f, MAIN / f) for f in ("fig_recovery_main.json", "fig_recovery_gauss.json",
                                                    "fig2_data_aos.json", "fig2_small_aos.json", "REPORT.md")]
        res = same_files(pairs)
        n_id = sum(v == "identical" for v in res.values())
        record("tables", f"scripts/aos_main_tables.py --rhc-covariates paper reproduces the stored outputs: "
                         f"{n_id}/{len(res)} files identical"
               + ("" if n_id == len(res) else f" (differing: {[k for k, v in res.items() if v != 'identical']})")
               + ".", res)
    elif stage == "cohort":
        pairs = [(arg / "tables" / f, TAB / f) for f in ("aos_main_cohort_macros.tex", "aos_main_cohort.tex",
                                                          "aos_main_cohort_balance.tex")] + [
            (arg / "main" / f, MAIN / f) for f in ("cohort_summary.json", "cohort_smd.csv", "cohort_compare.json",
                                                    "COHORT.md")]
        res = same_files(pairs)
        n_id = sum(v == "identical" for v in res.values())
        only_stamp = [k for k, v in res.items() if v != "identical" and v["differing_lines"] == 1
                      and all("Generated by" in (x or "") for pair in v["examples"] for x in pair)]
        record("cohort", f"scripts/aos_main_cohort.py --covariates paper reproduces the stored outputs: {n_id}/"
                         f"{len(res)} files identical"
               + (f", {only_stamp} differ only in the generation time stamp" if only_stamp else "")
               + ("" if n_id + len(only_stamp) == len(res) else
                  f"; DIFFERING: {[k for k, v in res.items() if v != 'identical' and k not in only_stamp]}") + ".",
               res)
    elif stage == "cohortrun":
        new = json.loads((arg / "pooled.json").read_text())
        old = json.loads((MAIN / "cohort" / "pooled.json").read_text())
        skip = {"seconds", "seconds_total", "seconds_fista", "seconds_smo", "seconds_polish", "timing"}

        def walk(a, b, path=""):
            out = []
            if isinstance(a, dict) and isinstance(b, dict):
                for k in sorted(set(a) | set(b)):
                    if k in skip or "seconds" in k:
                        continue
                    out += walk(a.get(k), b.get(k), f"{path}.{k}")
            elif isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
                for i, (x, y) in enumerate(zip(a, b)):
                    out += walk(x, y, f"{path}[{i}]")
            elif a != b:
                out.append(path)
            return out
        diff = walk(old, new)
        import numpy as np
        wa, wb = np.load(MAIN / "cohort" / "pooled.npz"), np.load(arg / "pooled.npz")
        same_w = all(np.array_equal(wa[k], wb[k]) for k in ("w", "v", "dx", "dy"))
        record("cohortrun", "scripts/aos_realdata_cohort.py --kernel laplace (default covariates) rerun of the pooled "
                            f"cohort: weights and witness values {'identical' if same_w else 'DIFFER'}, record fields "
                            f"other than wall times {'identical' if not diff else 'differing: ' + ', '.join(diff[:8])}.",
               {"weights_identical": same_w, "differing_fields": diff})
    elif stage == "analytic":
        a = [r for r in csv.DictReader(open(MAIN / "analytic_rd" / "tables" / "r12_valid_bandwidth.csv"))
             if r["dataset"] == "rhc"]
        b = list(csv.DictReader(open(arg / "tables" / "r12_valid_bandwidth.csv")))
        same = len(a) == len(b) and all(x == y for x, y in zip(a, b))
        record("analytic", f"scripts/exp_valid_bandwidth.py --threshold aos --pilot-only --datasets rhc (default "
                           f"covariates) rerun from an empty cache: {sum(x == y for x, y in zip(a, b))}/{len(a)} RHC rows "
                           f"of results/aos/main/analytic_rd/tables/r12_valid_bandwidth.csv identical.",
               {"identical": same})
    else:
        raise SystemExit(stage)


if __name__ == "__main__":
    main()
