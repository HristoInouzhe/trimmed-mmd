"""AoS revision: writes results/aos/baselines/REPORT.md from the template below, whose every number is a macro of
results/aos/tables/aos_baselines_macros.tex (written by scripts/aos_baselines_tables.py) or a replicate count read
from the raw files. No number in the report is typed by hand: placeholders are {{name}}.

    ~/.venvs/llm_book/bin/python -B scripts/aos_baselines_report.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
MAC = ROOT / "results" / "aos" / "tables" / "aos_baselines_macros.tex"
OUTD = ROOT / "results" / "aos" / "baselines"

TEMPLATE = r"""
# AoS referee baselines: report

*Generated by scripts/aos_baselines_report.py from results/aos/tables/aos_baselines_macros.tex and the raw replicates;
do not edit. Running log: NOTES.md. Code: scripts/aos_baselines_run.py (all new tests), scripts/aos_baselines_tables.py
(tables, macros), this script.*

__BODY__
"""


def macros():
    out = {}
    for line in MAC.read_text().splitlines():
        m = re.match(r"\\newcommand\{\\(\w+)\}\{(.*)\}$", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def counts():
    """Replicate counts and CPU seconds per job kind, from the raw files."""
    import json
    c = {k: 0 for k in ("main", "univ", "ks", "h00", "h00x")}
    cpu = {k: 0.0 for k in c}
    for f in (OUTD / "raw").glob("*.jsonl"):
        if f.name.startswith("calib"):
            continue
        k = next((s for s in ("univ", "ks", "h00x", "h00") if f.stem.endswith("_" + s)), "main")
        for line in f.read_text().splitlines():
            if line.strip():
                r = json.loads(line)
                c[k] += 1
                t = r.get("time") or {}
                cpu[k] += t.get("total", sum(v for v in t.values() if isinstance(v, (int, float))))
    out = {f"cnt{k.capitalize()}": f"{v:,}" for k, v in c.items()}
    out["cntAll"] = f"{sum(c.values()):,}"
    out["cpuHours"] = f"{sum(cpu.values()) / 3600:.1f}"
    return out


def calibration():
    """Per-replicate seconds from the calibration log (6 concurrent workers), and the wall clock of the run logs."""
    import statistics
    main, univ = [], {}
    for line in (OUTD / "calib.log").read_text().splitlines():
        m = re.match(r"(\S+)\s+n=\s*(\d+) total\s+([\d.]+)s", line)
        if not m:
            continue
        key, n, t = m.group(1), int(m.group(2)), float(m.group(3))
        if key.startswith("U1"):
            univ.setdefault(key, 0.0)
            univ[key] += t
        else:
            main.append(t)
    ref = []
    for line in (OUTD / "calib_n800.log").read_text().splitlines():
        m = re.match(r"(\S+)\s+n=\s*(\d+) total\s+([\d.]+)s", line)
        if m:
            ref.append(float(m.group(3)))
    stamps = []
    for f in [OUTD / "raw" / "discarded_v1" / "run_main_v1.log", OUTD / "logs" / "run_h00x.log"]:
        stamps += re.findall(r"^(\d\d):(\d\d):(\d\d) ", f.read_text(), flags=re.M)
    sec = [int(h) * 3600 + int(mi) * 60 + int(s_) for h, mi, s_ in stamps]
    wall = (max(sec) - min(sec)) / 3600
    return {"calMainMean": f"{statistics.mean(main):.1f}", "calMainMax": f"{max(main):.1f}",
            "calMainN": str(len(main)), "calUnivSet": f"{statistics.mean(univ.values()):.0f}",
            "wallHours": f"{wall:.1f}", "calRefMean": f"{statistics.mean(ref):.1f}"}


def main():
    from aos_baselines_report_body import BODY  # noqa: E402  (kept next to this file, see below)
    vals = macros() | counts() | calibration()
    text = TEMPLATE.replace("__BODY__", BODY)
    names = set(re.findall(r"\{\{(\w+)\}\}", text))
    missing = sorted(names - set(vals))
    assert not missing, f"placeholders without a generated value: {missing}"
    out = re.sub(r"\{\{(\w+)\}\}", lambda m: vals[m.group(1)], text).lstrip()
    (OUTD / "REPORT.md").write_text(out)
    print("wrote", OUTD / "REPORT.md", f"({len(names)} placeholders filled)")


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    main()
