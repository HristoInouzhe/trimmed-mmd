r"""AoS revision (2026-11-21, plan v1 S9): the further tests of the synthetic study, as a supplement table.

The written plan of the study (results/harder/DESIGN.md) ran, next to the four methods of the main text, further
certificates whose results were reported only in the code repository: a single split with betting on the ramp
(ramp_bet), a single split with an empirical-Bernstein closed form on the ramp (ramp_b2s), the split-sample DKW bound
(prop17), the percentile bootstrap (boot, asymptotic and per pair), and k-nearest neighbours with betting (knn_bet).
This script reads results/harder/summary_long.csv (written by scripts/harder_collect.py from the stored replicates)
and writes results/aos/tables/aos_extra_tests.tex: per design at its planned size (n = m = 800; mixed types n = 400),
power against H_{0,0}, the mean certified level over alpha*, and the rejection rate at the boundary alpha = alpha*.

    python3 -I scripts/aos_extra_tests_table.py
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "results" / "harder" / "summary_long.csv"
OUT = ROOT / "results" / "aos" / "tables" / "aos_extra_tests.tex"
DESIGNS = [
    ("D9_rhc", "RHC-shaped"), ("D1_d2_a10", r"overlap, $d=2$, $0.1$"), ("D1_d2_a20", r"overlap, $d=2$"),
    ("D1_d10_a10", r"overlap, $d=10$, $0.1$"), ("D1_d10_a20", r"overlap, $d=10$"), ("D2_d20", r"dense, $d=20$"),
    ("D2_d50", r"dense, $d=50$"), ("D2_d100", r"dense, $d=100$"), ("D3a_loc", "sparse shift"),
    ("D3b_corr", "corr.\\ flip"), ("D4_small", "small contam."), ("D5b_mixed", "mixed types"),
    ("D6_t3", "$t_3$ tails"), ("D7_wide", "wide bump"), ("D7_narrow", "narrow bump"), ("D8_N1", r"osc., $\nu=1$"),
    ("D8_N4", r"osc., $\nu=4$"), ("D8_N16", r"osc., $\nu=16$"), ("D8_N64", r"osc., $\nu=64$"),
]
METHODS = [("ramp_bet", "split, bet"), ("ramp_b2s", "split, EB"), ("prop17", "split, DKW"),
           ("boot", "bootstrap"), ("knn_bet", "$k$NN, bet")]


def main():
    rows = list(csv.DictReader(SRC.open()))
    have = {r["design"] for r in rows}
    lines = [r"% Generated by scripts/aos_extra_tests_table.py from results/harder/summary_long.csv -- do not edit.",
             r"\begin{tabular}{l" + "ccc" * len(METHODS) + "}", r"\toprule",
             " & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{{lab}}}" for _, lab in METHODS) + r" \\",
             " & " + " & ".join(["pow.", "rec.", "bd."] * len(METHODS)) + r" \\", r"\midrule"]
    worst = 0.0
    for key, lab in DESIGNS:
        if key not in have:
            continue
        sel = [r for r in rows if r["design"] == key]
        nmax = 800 if any(int(r["n"]) == 800 for r in sel) else max(int(r["n"]) for r in sel)
        cells = []
        for m, _ in METHODS:
            r = [x for x in sel if x["method"] == m and int(x["n"]) == nmax]
            if not r:
                cells += ["--", "--", "--"]
                continue
            r = r[0]
            a = float(r["alpha_star"])
            rec = float(r["alo_mean"]) / a if a > 0 else float("nan")
            worst = max(worst, float(r["typeI"]))
            cells += [f"{float(r['pow0']):.2f}", f"{rec:.2f}", f"{float(r['typeI']):.3f}"]
        lines.append(lab + (r" ($n{=}400$)" if nmax != 800 else "") + " & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    mac = OUT.with_name("aos_extra_tests_macros.tex")
    mac.write_text("% Generated by scripts/aos_extra_tests_table.py -- do not edit.\n"
                   f"\\newcommand{{\\xtBoundaryMax}}{{{worst:.3f}}}\n")
    print(f"wrote {OUT} and {mac}; largest boundary rejection rate {worst:.3f}")


if __name__ == "__main__":
    main()
