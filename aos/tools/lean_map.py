#!/usr/bin/env python3
r"""Write the map from the numbered results of the AoS version to their Lean theorems (StatFormal repository).

Reads the printed numbers from aos/main.aux and aos/supplement.aux (run build.sh first) and the label -> Lean alias rows
of the StatFormal reader pages Papers/TrimmedMMDJMLR/README.md and Papers/TrimmedMMD/README.md, and writes
<StatFormal>/docs/trimmed-mmd-aos.md: one row per numbered result in printed order, with its Lean aliases, status and
fidelity cards. Labels that the formalization carries under another name are mapped explicitly (ALIAS_LABELS); results
not formalized are listed with the reason (NOT_FORMALIZED).

    python3 -I aos/tools/lean_map.py [path to the StatFormal checkout, default ~/projects/StatFormal-tmmd-aos]
"""
import re
import subprocess
import sys
from pathlib import Path

AOS = Path(__file__).resolve().parents[1]
LEAN = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "projects" / "StatFormal-tmmd-aos"
OUT = LEAN / "docs" / "trimmed-mmd-aos.md"
KINDS = r"(?:thm|lem|prop|cor|ex|rem|ass|alg)"
NAMES = {"thm": "Theorem", "lem": "Lemma", "prop": "Proposition", "cor": "Corollary", "ex": "Example", "rem": "Remark",
         "ass": "Assumption", "alg": "Algorithm"}
# Labels whose prefix differs from the printed environment (cor:trimrate is printed as Theorem 6.1).
KIND_OVERRIDE = {"cor:trimrate": "Theorem"}
# AoS labels whose certified targets carry another label in StatFormal (same printed statement).
ALIAS_LABELS = {
    "lem:plugin": ["lem:plugin-det"],            # NOTE Lemma P0 (Wave30tp), printed as Lemma S2.2
    "thm:loratemain": ["prose:lo-rate", "thm:lorate"],   # main-text form of Theorem S4.6 (ii)-(iii) (Wave31tl lorate_O)
}
NOT_FORMALIZED = {}
# Rows whose StatFormal status text predates a later wave that completed them (counted as certified).
STATUS_OVERRIDE = {
    "prop:newslope": "certified: the first two sentences in earlier waves, the last sentence (continuous densities on a connected domain) in wave 31tr (T29)",
    "prop:newrates": "certified: part (i) (general margin) in waves 31to and 31tr (T10, T25); part (ii) (exponential margin) and the rate of part (iii) (Gaussian kernel) in wave 31tu (Y25 newrates_ii_exp, Y26 newrates_iii_gauss), for the run class of Theorem S4.3, which contains the paper's run",
    "cor:trimrate": "certified (cor_trimrate_v2): the precise form printed at the start of its proof in Section S5 (constants depending on the probability level alone, from a size depending on the laws), of which the O_P display of the main text is the reading",
}
PARTIAL = {}


def printed():
    out = []
    for doc in ("main", "supplement"):
        t = (AOS / f"{doc}.aux").read_text()
        for m in re.finditer(r"\\newlabel\{(" + KINDS + r":[^}]*)\}\{\{([^}]*)\}", t):
            out.append((doc, m.group(1), m.group(2)))
    return out


def lean_rows():
    rows = {}
    for page in ("TrimmedMMDJMLR", "TrimmedMMD"):
        for line in (LEAN / "Papers" / page / "README.md").read_text().splitlines():
            m = re.match(r"\| `([^`]*)` \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|$", line)
            if m and m.group(1) not in rows:
                aliases = re.findall(r"`([^`]+)`", m.group(3))
                cards = re.sub(r"\(\.\./\.\./certify/cards/", "(../certify/cards/", m.group(5))
                rows[m.group(1)] = (page, aliases, m.group(4), cards)
    return rows


def short(status, n=230):
    s = status.replace("|", "/")
    return s if len(s) <= n else s[:n].rsplit(" ", 1)[0] + " …"


def main():
    rows = lean_rows()
    head = subprocess.run(["git", "-C", str(AOS.parent), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    lines = [
        "# Trimmed MMD, Annals of Statistics version: printed results → Lean",
        "",
        f"Paper: *Certifying total-variation contamination by betting on trimmed kernel witnesses*, Annals of Statistics version "
        f"(trimmed-mmd repository, `aos/`, commit `{head}`). Numbers are those printed in the main text and the supplement (S…).",
        "Aliases live in `Papers.TrimmedMMDJMLR` (or `Papers.TrimmedMMD` for results kept from the long version); the labels are",
        "the paper's LaTeX labels. \"Certified\" means what [TRUST.md](../TRUST.md) says: the Lean theorem proves the hash-locked frozen",
        "claim with only `propext`, `Classical.choice` and `Quot.sound`; whether the frozen claim says what the paper says is the",
        "fidelity review on the card. Generated by `aos/tools/lean_map.py` of the paper repository.",
        "",
        "| printed | label | Lean alias(es) | status | card(s) |",
        "|---|---|---|---|---|",
    ]
    counts = {"certified": 0, "partial": 0, "not": 0, "def": 0}
    for doc, lab, num in printed():
        kind = KIND_OVERRIDE.get(lab) or NAMES[lab.split(":")[0]]
        name = {"rem:sharper": f"Section {num} (the sharper threshold)"}.get(lab, f"{kind} {num}")
        if lab in NOT_FORMALIZED:
            lines.append(f"| {name} | `{lab}` | — | {NOT_FORMALIZED[lab]} | — |")
            counts["not"] += 1
            continue
        keys = ALIAS_LABELS.get(lab, [lab])
        found = [rows[k] for k in keys if k in rows]
        if not found:
            raise SystemExit(f"no Lean row for {lab} ({name}); add it to ALIAS_LABELS or NOT_FORMALIZED")
        page = found[0][0]
        aliases = [f"`{a}`" for r in found for a in r[1]]
        status = PARTIAL.get(lab) or STATUS_OVERRIDE.get(lab) or short(found[0][2])
        if lab.startswith("ass:"):
            status = "definition: encoded as hypotheses of the certified statements (" + short(found[0][2], 120) + ")"
            counts["def"] += 1
        elif lab in PARTIAL:
            counts["partial"] += 1
        else:
            counts["certified"] += 1
        cards = ", ".join(dict.fromkeys(c for r in found for c in r[3].split(", ") if c and c != "—")) or "—"
        ns = "" if page == "TrimmedMMDJMLR" else f" ({page})"
        alias_cell = "<br>".join(aliases[:8]) + (f"<br>… {len(aliases) - 8} more" if len(aliases) > 8 else "")
        lines.append(f"| {name} | `{lab}`{ns} | {alias_cell} | {status} | {cards} |")
    lines += [
        "",
        f"Summary: {counts['certified']} results certified, {counts['partial']} certified in part, {counts['not']} not formalized, "
        f"{counts['def']} assumptions encoded as hypotheses.",
        "",
        "## Classical results",
        "",
        "* No textbook bridge remains. `ContainsSmoothCompact` (the RKHS of a Matérn kernel on ℝᵈ contains a smooth compactly",
        "  supported function with prescribed values on separated bounded sets), used for the sentence after Example 5.2, is now",
        "  proved from the Matérn spectral density (card [wave31tp](../certify/cards/wave31tp.md), L19b and L29), and every element",
        "  of the Gaussian RKHS, the witness of the remark on quantile densities (rem:qdens) included, is certified C^∞ and vanishing at infinity (L30).",
        "* The one-dimensional claims of the remark on quantile densities (rem:qdens, card [wave31tc](../certify/cards/wave31tc.md)) are",
        "  composed with the certified C¹/C^∞ regularity and decay of the witness (wave31th, wave31tp L30) in wave 31tr (T13).",
        "Ville's inequality, the Bernstein, McDiarmid, Maurer–Pontil, Pinelis and Dvoretzky–Kiefer–Wolfowitz inequalities, the density",
        "argument of that remark, Plancherel's theorem, Bochner's theorem for integrable positive-definite functions, Fourier feature",
        "maps and the native-space norm of translation-invariant kernels, and the Gaussian, Laplace and Matérn spectra are proved in the",
        "library (card wave31tp), not assumed.",
        "",
        "## Declared assumptions and caveats",
        "",
        "* The paper's own run is certified (wave 31tr, card [wave31tr](../certify/cards/wave31tr.md)): a measurable selection of an exact",
        "  minimizer, the genuine-quantile cut points, the pairing and the fractions, at the kernel level for the median-bandwidth rule and both",
        "  kernels. Declared there: the solver's output for an inexact solver is assumed measurable; the random order of the observations is",
        "  encoded as a fixed order, so the eight real-data splits are conditional on their permutations; the composed real-data bandwidth rule",
        "  (standardization, then the median heuristic) is assembled from certified ingredients rather than frozen as one claim.",
        "* Theorem 5.11 and Theorem S4.19 (wave 31tu, card [wave31tu](../certify/cards/wave31tu.md)) cover the run class of Theorem S4.3",
        "  with exact minimizers and genuine quantile cut points; the median-distance bandwidth and the iterative solver of the runs, and the",
        "  interpolated cut points of the simulation on the line, are outside them, as the paper says. Readings declared on the card: a grid",
        "  with J <= n∧m for \"a grid of that mesh\", n∨m <= (n∧m)^k for \"comparable size\", the fraction bounds in place of the printed",
        "  v0^2 <= 4, and no X equal to a Y for \"pooled points pairwise distinct\".",
        "* The Proposition 5.5 instance of Proposition 5.10(ii) is certified in wave 31tq (Q26).",
        "* The rate half of the Section 8 classifier sentence (Audibert-Tsybakov plug-in rates) is not formalized.",
        "",
        "## Declared, not formalized",
        "",
        "Every numbered result is certified. Declared and not formalized: the geometric-measure-theory sentences of wave 31tq (the",
        "general-hypersurface form of the R^d lower bound beyond the stated (G)-conditions); the numerical sentences of Section S6; the",
        "open questions the paper states (a constant of Theorem 5.11 uniform over a natural class, self-clipping under an inexact solve,",
        "Theorem 5.11(i) without condition (5.1), other kernels, R^d, data-driven kernels, whether the dimension enters the rate); and",
        "the discussion remarks of Section 8 (unequal trimming fractions and the hockey-stick divergence).",
        "",
        "## Notation and records",
        "",
        "The cards were written against earlier drafts of the paper, and some rows above quote their notation. Since then the",
        "numbered statements have changed only in notation and wording, and an independent check compared each change with its",
        "certified claim. Printed symbols and the names they had: n_{1-α} was n_α (Proposition 2.5, Lemmas S3.2 and S5.3); 𝒲 was 𝒩",
        "(Propositions 5.4 and S4.7); j and C_j were N and C_N (Proposition 5.6); ξ was Ω (Lemma S4.12, Theorem S4.13); ŝ and s⋆",
        "were ĝ and g⋆ (Lemmas S4.21, S4.22 and S4.26); τ^S was τ^A, still `tauA`, `thmA*` and the label `eq:tauA` in Lean;",
        "\"predictable\" was \"admissible\", still `IsAdmissible`, `IsFitRule`, `IsFracRule` and `IsBatchBetRule` in Lean.",
        "",
        "* Theorem 6.1 (`cor:trimrate`) is printed in O_P form; the precise form that the card certifies (constants depending on η",
        "  alone, from a size n_η on) opens its proof in Section S5. Pointers to \"§6 :62-64\" on the card wave31tq refer to that sentence.",
        "* The size condition of Theorem 5.11, \"for samples of comparable size\", is read as n∨m <= (n∧m)^k (card wave31tu).",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {counts}")


if __name__ == "__main__":
    main()
