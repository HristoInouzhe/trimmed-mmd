"""Copy the label records of one document into a .tex file read by the other (imsart forbids the xr package).

  python3 tools/supp_refs.py                 # supplement.aux -> supp_refs.tex (read by main.tex)
  python3 tools/supp_refs.py --reverse       # main.aux -> main_refs.tex (read by supplement.tex)

Each \\newlabel keeps its number and cleveref type; the hyperlink anchor is set to Doc-Start so that a reference to
the other document prints correctly without a dangling link. Labels defined in the reading document are skipped."""
import re, sys
from pathlib import Path
P=Path(__file__).resolve().parents[1]
rev='--reverse' in sys.argv
src,dst,reader=(('main.aux','main_refs.tex','supplement.tex') if rev else ('supplement.aux','supp_refs.tex','main.tex'))
aux=(P/src).read_text(errors='ignore')
srcs=[P/reader]+sorted((P/('supplement' if rev else 'sections')).glob('*.tex'))
own=set().union(*(re.findall(r'\\label\{([^}]+)\}',f.read_text()) for f in srcs))
out=[f'% Generated by tools/supp_refs.py from {src}; do not edit.','\\makeatletter']
n=0
for line in aux.splitlines():
    m=re.match(r'\\newlabel\{([^}]+)\}\{(.*)\}$',line)
    if not m: continue
    lab=m.group(1); base=lab[:-5] if lab.endswith('@cref') else lab
    if base in own or lab.startswith('tocindent'): continue
    if not lab.endswith('@cref'):
        parts=re.findall(r'\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}',m.group(2))
        if len(parts)>=4: parts[3]='Doc-Start'
        line=r'\newlabel{%s}{{%s}}'%(lab,'}{'.join(parts)); n+=1
    out.append(line)
out.append('\\makeatother')
(P/dst).write_text('\n'.join(out)+'\n')
print(f'{dst}: {n} labels from {src}')
