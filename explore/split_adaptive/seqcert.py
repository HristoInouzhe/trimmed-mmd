"""Sequential (multi-batch) split certificate: refit the witness on everything
seen so far, bet on the next batch. A finite-sample replacement for
cross-fitting.

Rows of each sample are put in a fixed random order and cut at fractions
edges = [0, e_1, ..., 1]. Batch b (b >= 1) is scored with a witness, cut points
and betting fractions computed from batches 0..b-1 only. The wealth

    K_t = prod_{k <= t} (1 + lam_k (Z_k - alpha)),   Z_k = g_{b(k)}(X_k) - mean g_{b(k)}(Y-block_k)

is a nonnegative supermartingale under H0 for the filtration generated by the
batches, so P(max_t K_t >= 1/delta) <= delta (Ville), for every n.
"""

from __future__ import annotations

import math

import numpy as np

import sacert as S
from fold1 import Witness, cut_points, pair_var


def batch_bounds(n, edges):
    return [int(round(e * n)) for e in edges]


def seq_ramp_bet(X, Y, alpha, edges, sigma, rng, delta=0.05, c=0.5, prior_w=20.0,
                 fit=None, return_parts=False):
    """X, Y already in random order. sigma must be a function of batch 0 only.

    fit(Xf, Yf, alpha) -> (callable witness, u_fit_selfexcl, v_fit_selfexcl);
    default: exact-Gram trimmed-MMD witness.
    """
    n, m = len(X), len(Y)
    bx, by = batch_bounds(n, edges), batch_bounds(m, edges)
    if fit is None:
        def fit(Xf, Yf, a):
            w = Witness(Xf, Yf, a, sigma, rng)
            u1, v1 = w.fold1_values()
            return w, u1, v1
    Zs, pri = [], []
    for b in range(1, len(edges) - 1):
        Xf, Yf = X[:bx[b]], Y[:by[b]]
        Xb, Yb = X[bx[b]:bx[b + 1]], Y[by[b]:by[b + 1]]
        wit, u1, v1 = fit(Xf, Yf, alpha)
        s, sp = cut_points(u1, v1, alpha)
        if not s > sp or len(Xb) == 0 or len(Yb) == 0:
            continue
        G, H = S.ramp(wit(Xb), s, sp), S.ramp(wit(Yb), s, sp)
        Zs.append(S.pair_up(G, -H) - alpha)
        Gf, Hf = S.ramp(u1, s, sp), S.ramp(v1, s, sp)
        pri.append(max(pair_var(Gf.var(), Hf.var(), len(Xb), len(Yb)), 1e-4))
    if not Zs:
        return (False, -np.inf) if not return_parts else (False, -np.inf, [])
    N = sum(z.size for z in Zs)
    L = math.log(1.0 / delta)
    lam_max = c / (1.0 + alpha)
    logK, best = 0.0, -np.inf
    # predictable variance: prior of the current batch, updated with past bets
    ssd, cnt, mu_sum = 0.0, 0, 0.0
    for z, pv in zip(Zs, pri):
        for y in z:
            mu = mu_sum / (prior_w + cnt)
            sig2 = max((prior_w * pv + ssd) / (prior_w + cnt), 1e-8)
            lam = min(lam_max, math.sqrt(2.0 * L / (N * sig2)))
            logK += math.log1p(lam * y)
            best = max(best, logK)
            ssd += (y - mu) ** 2
            mu_sum += y
            cnt += 1
    rej = best >= L
    return (rej, logK) if not return_parts else (rej, logK, Zs)
